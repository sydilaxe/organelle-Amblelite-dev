"""The voice abstractions, one per layer: al-drone.pd, al-sub.pd, al-pad.pd, al-perc1..4.pd (argument: the voice
number). A voice:
  [r al-<L>-n]  'voice note glide_ms'   the pitch (MIDI note) gliding over glide_ms (0 = a jump)
  [r al-<L>-g]  'voice vel'             the envelope: vel > 0 attack (from where it is), 0 release
  [r al-percN-hit] 'voice note vel dec' a strike (a percussion lane)
Everything that makes sound is in [pd dsp], switched off once the voice has been silent for a moment.
Signal path: the selected engine -> the layer's filter (Cutoff, Reso; fully open = bypassed) -> the envelope (not
on percussion: its engines shape their own strikes) -> a place in the stereo field -> throw~ al-<L>-L / -R."""
from pdlib import Canvas
from dsp import mul, add, sub, engine_canvas, out, span
import model as M
from model import S, ENGINES, VOICES
from engines import BUILD

# per-voice stereo place (0..1); pads spread, percussion by the Spread knob
PAD_PAN = [0.12, 0.38, 0.62, 0.88]
PERC_PAN = [-0.35, 0.0, 0.35]                               # around the lane's own place, x Spread
LANE_PAN = dict(perc1=0.3, perc2=0.7, perc3=0.5, perc4=0.15)


def env_ms():
    """the envelope times from the layer's ENV page (0..1): attack 1 ms .. 8 s, decay 5 ms .. 15 s, release 5 ms
    .. 20 s, all exponential"""
    return dict(A="pow(8000, {})", D="5*pow(3000, {})", R="5*pow(4000, {})")


def voice(L):
    perc = M.kind(L) == "perc"
    v = Canvas(w=1400, h=900)
    v.comment(f"al-{L}: one voice of the {L} layer (argument: its number) - generated by tools/voice.py", 20, 5)
    dsp = Canvas("dsp", w=2400, h=1400)
    v.cx, v.cy = 20, 40
    # ---- control (always on): note, gate, switching the DSP on and off
    on = v.obj("delay")                               # (switches the DSP off when it fires)
    swo = v.obj(f"s $0-sw")
    v.c(v.m(on, "0"), 0, swo, 0)
    A, D, Sus, R = (S(L, None, n) for n in ("Attack", "Decay", "Sustn", "Releas")) if not perc else (0, 0, 0, 0)
    GA, GD, GS, GR = (S(L, None, n) for n in ("GAtk", "GDec", "GSus", "GRel")) if not perc else (0, 0, 0, 0)
    if perc:
        hit = v.ch(v.recv(f"al-{L}-hit"), "route $1", "t l b")
        v.c(v.m((hit, 1), "stop"), 0, on, 0)
        v.c(v.m((hit, 1), "1"), 0, swo, 0)
        up = v.to((hit, 0), "unpack f f f")
        # the DSP stays on for the decay and a little more
        v.c(v.to((up, 2), "expr $f1*1.25 + 300"), 0, on, 0)
        pk = v.obj("pack f f f")
        v.c((up, 2), 0, pk, 2)
        v.c((up, 1), 0, pk, 1)
        v.c(v.to((up, 0), "mtof"), 0, pk, 0)
        # a voice struck again while it still rings (a long Decay): faded out over 2 ms first, then struck - its
        # oscillators and envelopes restart from silence, not under a loud tail (that was a click). Every strike
        # waits the same 5 ms, so the timing stays even
        dk = v.obj("s $0-dk")
        v.c(v.m((hit, 1), "0 2"), 0, dk, 0)
        held = v.obj("list")
        v.c(pk, 0, held, 1)
        v.c(v.ch(pk, "t b", "delay 5"), 0, held, 0)
        st = v.to(held, "t b l")
        v.c((st, 1), 0, v.obj("s $0-strike"), 0)
        v.c(v.m((st, 0), "1"), 0, dk, 0)
    else:
        n = v.ch(v.recv(f"al-{L}-n"), "route $1")
        v.c(v.m(n, "$1 $2"), 0, v.obj("s $0-pitch"), 0)
        lastn = v.obj("f")
        v.c(v.ch(n, "unpack f f", "mtof"), 0, lastn, 1)
        # 'vel set': set 1 = a gate's hit (the GATENV envelope), 0 = a note you play (ENV). Times read with
        # their LFO and Evolve movement (alpe)
        gu = v.ch(v.recv(f"al-{L}-g"), "route $1", "unpack f f")
        g = v.to(gu, "t f f")
        sel = v.to((g, 0), "sel 0")
        # release: to 0 over R, the DSP off after it
        rel = v.to(sel, "t b b")
        rx = v.obj(f"expr if($f2, {env_ms()['R'].format(f'alpe[{GR}]')}, {env_ms()['R'].format(f'alpe[{R}]')})")
        v.c((gu, 1), 0, rx, 1)
        v.c((rel, 0), 0, rx, 0)
        v.c(v.m(rx, "0 $1"), 0, v.obj("s $0-env"), 0)
        v.c(v.to(rx, "+ 150"), 0, on, 0)
        # attack: switch on, then up to the velocity over A, then down to the sustain over D
        att = v.to((sel, 1), "t f b b")
        v.c(v.m((att, 2), "stop"), 0, on, 0)
        v.c(v.m((att, 1), "1"), 0, swo, 0)
        ax = v.obj(f"expr sqrt($f1); if($f2, {env_ms()['A'].format(f'alpe[{GA}]')}, {env_ms()['A'].format(f'alpe[{A}]')}); "
                   f"sqrt($f1*if($f2, alpe[{GS}], alpe[{Sus}])); "
                   f"if($f2, {env_ms()['D'].format(f'alpe[{GD}]')}, {env_ms()['D'].format(f'alpe[{D}]')})")
        v.c((gu, 1), 0, ax, 1)
        v.c((att, 0), 0, ax, 0)
        pk = v.obj("pack f f f f")
        for i in (3, 2, 1, 0):
            v.c(ax, i, pk, i)
        v.c(v.m(pk, "$1 $2, $3 $4 $2"), 0, v.obj("s $0-env"), 0)
        # the engines hear each note-on: 'hz vel'
        tf = v.ch((g, 1), "moses 0.0001")
        tbf = v.to((tf, 1), "t b f")
        lv = v.obj("pack f f")
        v.c(tbf, 1, lv, 1)
        v.c(tbf, 0, lastn, 0)
        v.c(lastn, 0, lv, 0)
        v.c(lv, 0, v.obj("s $0-note"), 0)
    v.sub(dsp)

    # ---- the DSP
    d = dsp
    d.comment("everything that sounds: switched off while the voice is silent")
    sw = d.obj("switch~")
    d.c(d.recv("$0-sw"), 0, sw, 0)
    d.c(d.m(d.obj("loadbang"), "0"), 0, sw, 0)
    slow = None if perc else _slow(L)
    if perc:
        strike = d.recv("$0-strike")
        env = None
    else:
        sl = d.sub(slow)
        # MPE: the note's own pitch bend (semitones) and pressure (its level), from midi.py
        bend = d.ch(d.recv(f"al-{L}-b"), "route $1", "pack f 12", "line~")
        expr_ = d.ch(d.recv(f"al-{L}-x"), "route $1", "pack f 20", "line~")
        d.c(d.m(d.obj("loadbang"), "1"), 0, expr_, 0)
        # (the pitch's glide: [line~], which keeps no queue - a silent voice, switched off, still hears every
        # chord change, and a [vline~] would pile them up until it played again)
        f = d.to(add(d, add(d, d.to(d.recv("$0-pitch"), "line~"), (sl, 0)), bend), "mtof~")
        ev = d.ch(d.recv("$0-env"), "vline~")
        env = mul(d, ev, ev)
        note = d.recv("$0-note")
    engs = M.engines(L)
    ne = len(engs)
    esel = d.ch(d.recv(f"al-s{S(L, None, 'Engine')}"), f"expr min({ne - 1}, int($f1*{ne}))",
                "t " + " ".join(["f"] * ne))
    sL, sR = d.obj("+~"), d.obj("+~")
    d.col(260)
    for k, (en, _) in enumerate(engs):
        ec, ins, gain = engine_canvas(en, perc)
        Lo, Ro = BUILD[(M.kind(L), en)](ec, ins, L)
        out(ec, Lo, Ro, gain)
        node = d.sub(ec)
        on = d.to((esel, ne - 1 - k), f"expr $f1 == {k}")
        d.c(on, 0, node, 0)
        # (the messages - a strike, a note - only to the engine that plays: one switched off would queue them in its
        # [vline~]s, never played out, a little more at every note - the CPU climbing over a long session)
        gate = d.obj("spigot")
        d.c(on, 0, gate, 1)
        d.c(gate, 0, node, 1 if perc else 3)
        if perc:
            d.c(strike, 0, gate, 0)
        else:
            d.c(f, 0, node, 1)
            d.c(env, 0, node, 2)
            d.c(note, 0, gate, 0)
        d.c(node, 0, sL, 0)
        d.c(node, 1, sR, 0)
    d.col(260)
    # (the layer's filter is on its bus: gen.mix)
    outs = []
    for x in (sL, sR):
        outs.append(mul(d, mul(d, x, env), expr_) if env is not None else x)
    if not perc:
        outs = [mul(d, x, (sl, 1)) for x in outs]
    else:
        # ([vline~]: exact to the sample, as the envelopes it restarts with - [line~] would turn back up at the
        # block's start, before them)
        dk = d.ch(d.recv("$0-dk"), "vline~")
        d.c(d.m(d.obj("loadbang"), "1"), 0, dk, 0)
        outs = [mul(d, x, dk) for x in outs]
    # ---- its place in the stereo field
    if L == "pad":
        oL, oR = mul(d, outs[0], (sl, 2)), mul(d, outs[1], (sl, 3))
    elif perc:
        # (the lane's Spread places its voices: gains worked out at control rate, ramped)
        k = d.ch(d.obj("loadbang"), "f $1", "expr " + " ".join(
            f"if($f1 == {i}, {p}," for i, p in enumerate(PERC_PAN[:-1])) + f" {PERC_PAN[-1]}" + ")" * (len(PERC_PAN) - 1))
        g = d.obj(f"expr 1.414*cos(1.5708*max(0, min(1, $f1*$f2 + {LANE_PAN[L]}))); "
                  f"1.414*sin(1.5708*max(0, min(1, $f1*$f2 + {LANE_PAN[L]})))")
        d.c(k, 0, g, 1)
        d.c(d.recv(f"al-s{S(L, None, 'Spread')}"), 0, g, 0)
        oL = mul(d, outs[0], d.ch((g, 0), "pack f 25", "line~"))
        oR = mul(d, outs[1], d.ch((g, 1), "pack f 25", "line~"))
    else:
        oL, oR = outs
    d.c(oL, 0, d.obj(f"throw~ al-{L}-L"), 0)
    d.c(oR, 0, d.obj(f"throw~ al-{L}-R"), 0)
    return v


def _slow(L):
    """the voice's slow movement, at 1/16 of the audio rate (as Amble: block 4 = one parent block, held back up):
    pitch drift (the layer's Drift: two slow sines, up to about 1/3 semitone), Evolve's breathing in level (pads:
    each voice on its own cycle; drone and sub gently) and, pads, the orbit around the voice's place.
    Outlets: drift (semitones), the breath gain, and (pads) the left and right gains."""
    v = Canvas("slow", w=1400)
    v.obj("block~ 4 1 0.0625")
    dr = v.ch(v.recv(f"al-s{S(L, None, 'Drift')}"), "expr $f1*$f1*0.35", "pack f 60", "line~")
    lb = v.ch(v.obj("loadbang"), "f $1", "t f f")
    o1, o2 = v.obj("osc~ 0.137"), v.obj("osc~ 0.084")
    v.c(v.to((lb, 1), "expr 0.137 + $f1*0.011"), 0, o1, 0)
    v.c(v.to((lb, 0), "expr 0.084 + $f1*0.017"), 0, o2, 0)
    v.c(v.to((lb, 1), "expr $f1*0.25"), 0, o1, 1)
    v.c(v.to((lb, 0), "expr $f1*0.4"), 0, o2, 1)
    drift = mul(v, dr, add(v, v.to(o1, "*~ 0.6"), v.to(o2, "*~ 0.4")))
    v.c(drift, 0, v.obj("outlet~ hold", 20, 1100), 0)
    ev = v.ch(v.recv(f"al-evd{M.LAYERS.index(L)}"), "unpack f f")
    edep = v.ch(ev, "pack f 60", "line~")
    pad = L == "pad"
    depth = 0.3 if pad else 0.15
    bf = v.obj("osc~ 0.01")
    fx = v.obj("expr 1/max(1, $f1*$f2)")
    if pad:
        v.c(v.ch(v.obj("loadbang"), "f $1", "expr if($f1 == 0, 0.11, if($f1 == 1, 0.14, if($f1 == 2, 0.17, 0.2)))"),
            0, fx, 1)
    else:
        v.c(v.m(v.obj("loadbang"), "0.15"), 0, fx, 1)
    v.c((ev, 1), 0, fx, 0)
    v.c(fx, 0, bf, 0)
    v.c(v.ch(v.obj("loadbang"), "f $1", "expr $f1*0.23"), 0, bf, 1)
    breath = v.ch(mul(v, v.ch(bf, "*~ 0.5", "+~ 0.5"), edep), f"*~ -{depth}", "+~ 1")
    v.c(breath, 0, v.obj("outlet~ hold", 220, 1100), 0)
    if pad:
        orbit = v.obj("osc~ 0.01")
        v.c(v.to(fx, "* 0.61"), 0, orbit, 0)
        orb = v.to(mul(v, orbit, edep), "*~ 0.25")
        home = v.ch(v.obj("loadbang"), "f $1", "expr " + " ".join(
            f"if($f1 == {i}, {p}," for i, p in enumerate(PAD_PAN[:-1])) + f" {PAD_PAN[-1]}" + ")" * (len(PAD_PAN) - 1))
        hp = v.to(orb, "+~ 0")
        v.c(home, 0, hp, 1)
        q = v.ch(hp, "clip~ 0 1", "*~ 0.25")
        v.c(v.ch(q, "cos~", "*~ 1.414"), 0, v.obj("outlet~ hold", 420, 1100), 0)
        v.c(v.ch(q, "-~ 0.25", "cos~", "*~ 1.414"), 0, v.obj("outlet~ hold", 620, 1100), 0)
    return v

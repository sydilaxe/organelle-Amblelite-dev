"""The voice abstractions, one per layer: al-drone.pd, al-sub.pd, al-pad.pd, al-perc.pd (argument: the voice
number). A voice:
  [r al-<L>-n]  'voice note glide_ms'   the pitch (MIDI note) gliding over glide_ms (0 = a jump)
  [r al-<L>-g]  'voice vel'             the envelope: vel > 0 attack (from where it is), 0 release
  [r al-perc-hit] 'voice note vel dec'  a strike (percussion)
Everything that makes sound is in [pd dsp], switched off once the voice has been silent for a moment.
Signal path: the selected engine -> the layer's filter (Cutoff, Reso; fully open = bypassed) -> the envelope (not
on percussion: its engines shape their own strikes) -> a place in the stereo field -> throw~ al-<L>-L / -R."""
from pdlib import Canvas
from dsp import mul, add, sub, engine_canvas, out, span
from model import S, ENGINES, VOICES
from engines import BUILD

# per-voice stereo place (0..1); pads spread, percussion by the Spread knob
PAD_PAN = [0.32, 0.44, 0.56, 0.68]
PERC_PAN = [-0.45, 0.45, -0.3, 0.3, -0.15, 0.15]


def env_ms():
    """the envelope times from the layer's ENV page (0..1): attack 1 ms .. 8 s, decay 5 ms .. 15 s, release 5 ms
    .. 20 s, all exponential"""
    return dict(A="pow(8000, {})", D="5*pow(3000, {})", R="5*pow(4000, {})")


def voice(L):
    perc = L == "perc"
    v = Canvas(w=1400, h=900)
    v.comment(f"al-{L}: one voice of the {L} layer (argument: its number) - generated by tools/voice.py", 20, 5)
    dsp = Canvas("dsp", w=2400, h=1400)
    v.cx, v.cy = 20, 40
    # ---- control (always on): note, gate, switching the DSP on and off
    on = v.obj("delay")                               # (switches the DSP off when it fires)
    swo = v.obj(f"s $0-sw")
    v.c(v.m(on, "0"), 0, swo, 0)
    A, D, Sus, R = (S(L, None, n) for n in ("Attack", "Decay", "Sustn", "Releas")) if not perc else (0, 0, 0, 0)
    if perc:
        hit = v.ch(v.recv("al-perc-hit"), "route $1", "t l b")
        v.c(v.m((hit, 1), "stop"), 0, on, 0)
        v.c(v.m((hit, 1), "1"), 0, swo, 0)
        up = v.to((hit, 0), "unpack f f f")
        # the DSP stays on for the decay and a little more
        v.c(v.to((up, 2), "expr $f1*1.25 + 300"), 0, on, 0)
        pk = v.obj("pack f f f")
        v.c((up, 2), 0, pk, 2)
        v.c((up, 1), 0, pk, 1)
        v.c(v.to((up, 0), "mtof"), 0, pk, 0)
        v.c(pk, 0, v.obj("s $0-strike"), 0)
    else:
        n = v.ch(v.recv(f"al-{L}-n"), "route $1")
        v.c(v.m(n, "$1 $2"), 0, v.obj("s $0-pitch"), 0)
        lastn = v.obj("f")
        v.c(v.ch(n, "unpack f f", "mtof"), 0, lastn, 1)
        g = v.ch(v.recv(f"al-{L}-g"), "route $1", "t f f")
        sel = v.to((g, 0), "sel 0")
        # release: to 0 over R, the DSP off after it
        rel = v.to(sel, "t b b")
        rx = v.obj(f"expr {env_ms()['R'].format(f'alp[{R}]')}")
        v.c((rel, 0), 0, rx, 0)
        v.c(v.m(rx, "0 $1"), 0, v.obj("s $0-env"), 0)
        v.c(v.to(rx, "+ 150"), 0, on, 0)
        # attack: switch on, then up to the velocity over A, then down to the sustain over D
        att = v.to((sel, 1), "t f b b")
        v.c(v.m((att, 2), "stop"), 0, on, 0)
        v.c(v.m((att, 1), "1"), 0, swo, 0)
        ax = v.obj(f"expr sqrt($f1); {env_ms()['A'].format(f'alp[{A}]')}; sqrt($f1*alp[{Sus}]); "
                   f"{env_ms()['D'].format(f'alp[{D}]')}")
        v.c((att, 0), 0, ax, 0)
        pk = v.obj("pack f f f f")
        for i in (3, 2, 1, 0):
            v.c(ax, i, pk, i)
        v.c(v.m(pk, "$1 $2, $3 $4 $2"), 0, v.obj("s $0-env"), 0)
        # the engines hear each note-on: 'hz vel'
        tf = v.ch((g, 1), "moses 0.0001")
        tbf = v.to((tf, 1), "t b f")
        lv = v.obj("pack f f")
        v.c(tbf, 1, lv, 1)
        v.c(tbf, 0, lastn, 0)
        v.c(lastn, 0, lv, 0)
        v.c(lv, 0, v.obj("s $0-note"), 0)
    v.sub(dsp)

    # ---- the DSP
    d = dsp
    d.comment("everything that sounds: switched off while the voice is silent")
    sw = d.obj("switch~")
    d.c(d.recv("$0-sw"), 0, sw, 0)
    d.c(d.m(d.obj("loadbang"), "0"), 0, sw, 0)
    if perc:
        strike = d.recv("$0-strike")
        env = None
    else:
        f = d.ch(d.recv("$0-pitch"), "vline~", "mtof~")
        ev = d.ch(d.recv("$0-env"), "vline~")
        env = mul(d, ev, ev)
        note = d.recv("$0-note")
    engs = ENGINES[L]
    ne = len(engs)
    esel = d.ch(d.recv(f"al-s{S(L, None, 'Engine')}"), f"expr min({ne - 1}, int($f1*{ne}))",
                "t " + " ".join(["f"] * ne))
    sL, sR = d.obj("+~"), d.obj("+~")
    d.col(260)
    for k, (en, _) in enumerate(engs):
        ec, ins, gain = engine_canvas(en, perc)
        Lo, Ro = BUILD[(L, en)](ec, ins)
        out(ec, Lo, Ro, gain)
        node = d.sub(ec)
        d.c(d.to((esel, ne - 1 - k), f"expr $f1 == {k}"), 0, node, 0)
        if perc:
            d.c(strike, 0, node, 1)
        else:
            d.c(f, 0, node, 1)
            d.c(env, 0, node, 2)
            d.c(note, 0, node, 3)
        d.c(node, 0, sL, 0)
        d.c(node, 1, sR, 0)
    d.col(260)
    # ---- the layer's filter: a 2-pole low-pass (biquad~), its coefficients from the layer (filters.py)
    outs = []
    for x in (sL, sR):
        bq = d.obj("biquad~ 0 0 1 0 0")
        d.c(d.recv(f"al-{L}-bq"), 0, bq, 0)
        d.c(x, 0, bq, 0)
        outs.append(mul(d, bq, env) if env is not None else bq)
    # ---- its place in the stereo field
    if L == "pad":
        pos = d.ch(d.obj("loadbang"), f"f $1", f"expr if($f1 == 0, {PAD_PAN[0]}, if($f1 == 1, {PAD_PAN[1]}, "
                                           f"if($f1 == 2, {PAD_PAN[2]}, {PAD_PAN[3]})))", "sig~")
        oL, oR = _place(d, outs, pos)
    elif perc:
        sp = d.ch(d.recv(f"al-s{S('perc', None, 'Spread')}"), "pack f 25", "line~")
        k = d.ch(d.obj("loadbang"), "f $1", "expr " + " ".join(
            f"if($f1 == {i}, {p}," for i, p in enumerate(PERC_PAN[:-1])) + f" {PERC_PAN[-1]}" + ")" * (len(PERC_PAN) - 1))
        pos = d.to(d.to(mul(d, sp, d.to(k, "sig~")), "+~ 0.5"), "clip~ 0 1")
        oL, oR = _place(d, outs, pos)
    else:
        oL, oR = outs
    d.c(oL, 0, d.obj(f"throw~ al-{L}-L"), 0)
    d.c(oR, 0, d.obj(f"throw~ al-{L}-R"), 0)
    return v


def _place(d, outs, pos):
    """a stereo signal placed at pos (0..1): each side kept, panned by the balance (mono-safe)"""
    q = d.to(pos, "*~ 0.25")
    gl = d.ch(q, "cos~", "*~ 1.414")
    gr = d.ch(q, "-~ 0.25", "cos~", "*~ 1.414")
    return mul(d, outs[0], gl), mul(d, outs[1], gr)
